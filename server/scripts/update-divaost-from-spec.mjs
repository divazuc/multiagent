async function main() {
  let updated = 0, activated = 0, missing = [];
  for (const u of UPDATES) {
    const patch = { answer: u.a, updated_at: new Date().toISOString() };
    if (u.nq) patch.question = u.nq;
    if (u.activate) { patch.is_active = true; patch.suggested = false; }
    const { data, error } = await supabase.from('knowledge_items')
      .update(patch).eq('business_id', BIZ).eq('question', u.q).select('id');
    if (error) throw error;
    if (!data?.length) { missing.push(u.q); continue; }
    updated += data.length;
    if (u.activate) activated += data.length;
  }

  const rows = NEW_ITEMS.map(i => ({
    business_id: BIZ, category: i.c, question: i.q, answer: i.a,
    language: 'he', archetypes: [], is_active: true, suggested: false,
  }));
  // guard: skip inserts that already exist (rerun safety)
  const { data: existing } = await supabase.from('knowledge_items')
    .select('question').eq('business_id', BIZ);
  const have = new Set((existing ?? []).map(r => r.question));
  const fresh = rows.filter(r => !have.has(r.question));
  if (fresh.length) {
    const { error } = await supabase.from('knowledge_items').insert(fresh);
    if (error) throw error;
  }

  const { data: prof, error: gErr } = await supabase.from('business_profiles')
    .select('guardrails').eq('business_id', BIZ).maybeSingle();
  if (gErr) throw gErr;
  const g = prof?.guardrails ?? {};
  const merge = (arr, adds) => [...new Set([...(arr ?? []), ...adds])];
  const { error: wErr } = await supabase.from('business_profiles').update({
    guardrails: {
      ...g,
      forbidden_custom: NEW_FORBIDDEN_CUSTOM,
      escalation_points: merge(g.escalation_points, ADD_ESCALATION),
      forbidden_topics: merge(g.forbidden_topics, ADD_FORBIDDEN),
    },
    updated_at: new Date().toISOString(),
  }).eq('business_id', BIZ);
  if (wErr) throw wErr;

  console.log(`updated ${updated} items (${activated} pending items resolved+activated)`);
  console.log(`inserted ${fresh.length} new items (${rows.length - fresh.length} already existed)`);
  console.log('guardrails rewritten: prices 999/1,499/2,999, iron rules added');
  if (missing.length) console.log('NOT FOUND (check manually):', missing);
}

main().catch(e => { console.error(e); process.exit(1); });
